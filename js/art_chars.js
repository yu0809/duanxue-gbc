// SPR[name] = { down:[a,b,c,d], up:[...], left:[...], right:[...] } walk cycles of 4
const SPR = {};
function buildCharSprites() {
  for (const name in CHAR_PAL) {
    const { tpl, map } = CHAR_PAL[name];
    const T = CHAR_TPL[tpl];
    const mk = (rows) => art(recolor(rows, map));
    if (T.mon) {
      const a = mk(T.down[0]), b = mk(T.down[1]);
      const cyc = [a, b, a, b];
      SPR[name] = { down: cyc, up: cyc, left: cyc, right: cyc, mon: true };
      continue;
    }
    const d0 = mk(T.down[0]), d1 = mk(T.down[1]);
    const u0 = mk(T.up[0]), u1 = mk(T.up[1]);
    const l0 = mk(T.left[0]), l1 = mk(T.left[1]);
    SPR[name] = {
      down: [d0, d1, d0, flipH(d1)],
      up: [u0, u1, u0, flipH(u1)],
      left: [l0, l1, l0, l1],
      right: [flipH(l0), flipH(l1), flipH(l0), flipH(l1)],
    };
  }
}
