const TILES = {};     // name -> { rows | frames, solid, over, ... }
const TILE_IMG = {};  // name -> canvas (first frame) — for gallery
const TILE_FR = {};   // name -> [canvas, ...] animation frames
function tile(name, rows, opt = {}) { TILES[name] = Object.assign({ rows }, opt); }
// cut a big drawing into named 16x16 tiles: name_x_y
function bigTile(name, rows, opt = {}) {
  const h = rows.length / 16, w = rows[0].length / 16;
  const meta = { w, h, parts: [] };
  for (let ty = 0; ty < h; ty++) for (let tx = 0; tx < w; tx++) {
    const part = [];
    for (let y = 0; y < 16; y++) part.push(rows[ty * 16 + y].slice(tx * 16, tx * 16 + 16));
    const o = typeof opt === 'function' ? opt(tx, ty, w, h) : opt;
    tile(`${name}_${tx}_${ty}`, part, o);
    meta.parts.push(`${name}_${tx}_${ty}`);
  }
  BIG[name] = meta;
}
