// ---------------- soft edges where snow meets a path ----------------
// Built per side as transparent overlays; mask bits 1=N 2=E 4=S 8=W
const EDGE_SETS = {
  snow: { lip: 'x', hi: 'W', sh: 'g' },
  grass: { lip: 'l', hi: 'L', sh: 'E' },
  moss: { lip: 'G', hi: 'v', sh: 'h' },
};
function edgeSide(side, set) {
  const g = Array.from({ length: 16 }, () => Array(16).fill('.'));
  const rnd = mulberry(side * 97 + 13);
  for (let i = 0; i < 16; i++) {
    const depth = 2 + (rnd() < 0.45 ? 1 : 0) + (rnd() < 0.15 ? 1 : 0);
    for (let d = 0; d < depth; d++) {
      const c = d === 0 && rnd() < 0.3 ? set.hi : set.lip;
      put(i, d, c);
    }
    if (rnd() < 0.7) put(i, depth, set.sh);
  }
  function put(i, d, c) {
    if (side === 0) g[d][i] = c;            // north: rows from top
    else if (side === 2) g[15 - d][i] = d === 0 ? c : (c === set.sh ? set.sh : c); // south
    else if (side === 3) g[i][d] = c;       // west
    else g[i][15 - d] = c;                  // east
  }
  // south edge reads as the near bank: no shadow, just the lip
  if (side === 2) for (let y = 0; y < 16; y++) for (let x = 0; x < 16; x++) if (g[y][x] === set.sh) g[y][x] = '.';
  return art(g.map((r) => r.join('')));
}
const EDGE_IMG = {};
function edgeImgs(setName) {
  if (!EDGE_IMG[setName]) EDGE_IMG[setName] = [0, 1, 2, 3].map((s) => edgeSide(s, EDGE_SETS[setName]));
  return EDGE_IMG[setName];
}

// ---------------- autotiling for water ----------------
// mask bits: 1=N land, 2=E land, 4=S land, 8=W land
function waterVariant(rows, mask, landLip = 'x', lipShade = 'w', dark = 'D') {
  const g = rows.map((r) => r.split(''));
  if (mask & 1) { for (let x = 0; x < 16; x++) { g[0][x] = landLip; g[1][x] = lipShade; g[2][x] = dark; } }
  if (mask & 4) { for (let x = 0; x < 16; x++) { g[15][x] = dark; } }
  if (mask & 8) { for (let y = 0; y < 16; y++) { g[y][0] = landLip; g[y][1] = lipShade; if (g[y][2] !== landLip && g[y][2] !== lipShade) g[y][2] = dark; } }
  if (mask & 2) { for (let y = 0; y < 16; y++) { g[y][15] = landLip; g[y][14] = lipShade; if (g[y][13] !== landLip && g[y][13] !== lipShade) g[y][13] = dark; } }
  return g.map((r) => r.join(''));
}
function shiftRows(rows, dx) {
  return rows.map((r, y) => {
    const s = (dx * (y % 4 < 2 ? 1 : -1) + 16) % 16;
    return r.slice(16 - s) + r.slice(0, 16 - s);
  });
}

// Build every tile image (with animation frames)
function buildTiles() {
  for (const name in TILES) {
    const t = TILES[name];
    let frames;
    if (t.frames) frames = t.frames;
    else if (t.anim === 'shift') frames = [t.rows, shiftRows(t.rows, 2)];
    else frames = [t.rows];
    TILE_FR[name] = frames.map((r) => art(r));
    TILE_IMG[name] = TILE_FR[name][0];
  }
}
// Lazily build autotile variants of water-like tiles
const AUTO_CACHE = {};
function autoTile(base, mask) {
  const key = base + mask;
  if (AUTO_CACHE[key]) return AUTO_CACHE[key];
  const t = TILES[base];
  const lip = t.lip || ['x', 'w', 'D'];
  const f0 = waterVariant(t.rows, mask, ...lip);
  const frames = t.anim === 'shift' ? [f0, waterVariant(shiftRows(t.rows, 2), mask, ...lip)] : [f0];
  return (AUTO_CACHE[key] = frames.map((r) => art(r)));
}
