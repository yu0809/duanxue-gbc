function rotate90(img) {
  const c = makeCanvas(img.height, img.width);
  const g = c.getContext('2d');
  g.translate(img.height, 0); g.rotate(Math.PI / 2); g.drawImage(img, 0, 0);
  return c;
}
function buildPartyBattle() {
  for (const id of ['shenmo', 'suli', 'linfeng']) {
    const { tpl, map } = CHAR_PAL[id];
    const T = CHAR_TPL[tpl];
    const base = T.left[0].map((r) => r.replace(/./g, (c) => (map[c] !== undefined ? map[c] : c)));
    const walk = T.left[1].map((r) => r.replace(/./g, (c) => (map[c] !== undefined ? map[c] : c)));
    const down = T.down[0].map((r) => r.replace(/./g, (c) => (map[c] !== undefined ? map[c] : c)));
    const withSword = (rows, key) => {
      if (id === 'suli') return rows; // she casts bare-handed
      const g = rows.map((r) => r.split(''));
      for (const [x, y, c] of SWORD_OVER[key] || []) g[y][x] = c;
      return g.map((r) => r.join(''));
    };
    const shiftDown = (rows, n) => Array(n).fill('.'.repeat(16)).concat(rows.slice(0, 16 - n));
    const shiftX = (rows, n) => rows.map((r) => (n > 0 ? '.'.repeat(n) + r.slice(0, 16 - n) : r.slice(-n) + '.'.repeat(-n)));
    // a crouched version: squash the legs
    const kneel = shiftDown(base.slice(0, 11), 3).slice(0, 14).concat(['....#33333##....'.replace(/3/g, map[3]).replace(/#/g, 'K'), '....########....'.replace(/#/g, 'K')]);
    const closedEyes = (rows) => rows.map((r, y) => (y >= 7 && y <= 9 ? r.replace(/K(?=[s]+K)/, 's') : r));
    const castRows = id === 'suli' ? patchRows(base, [[5, 11, map[1]], [4, 10, map[1]], [3, 9, 'c'], [2, 8, 'W'], [4, 8, 'c']]) : withSword(base, 'cast');
    BSPR[id] = {
      idle: [art(withSword(base, 'idle')), art(withSword(shiftDown(base, 1), 'idle'))],
      run: [art(withSword(base, 'idle')), art(withSword(walk, 'idle'))],
      attack: art(id === 'suli' ? patchRows(walk, [[4, 12, map[1]], [3, 12, 'c'], [2, 12, 'W']]) : withSword(shiftX(walk, -1), 'attack')),
      cast: art(castRows),
      hurt: art(closedEyes(shiftX(base, 1))),
      weak: art(withSword(kneel, 'idle')),
      guard: art(withSword(base, 'guard')),
      win: art(withSword(down, 'cast')),
      ko: null,
    };
    BSPR[id].ko = rotate90(art(closedEyes(down)));
    // mini face for the turn strip (16x10 crop of the head)
    const mini = makeCanvas(16, 10);
    mini.getContext('2d').drawImage(art(down), 0, 1, 16, 10, 0, 0, 16, 10);
    BATTLE_MINI[id] = mini;
  }
}
function patchRows(rows, px) {
  const g = rows.map((r) => r.split(''));
  for (const [x, y, c] of px) g[y][x] = c;
  return g.map((r) => r.join(''));
}

