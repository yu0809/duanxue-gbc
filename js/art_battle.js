function buildBattleArt() {
  buildPartyBattle();
  for (const [name, fam] of Object.entries(EPAL)) {
    const pal = Object.keys(fam)[0];
    const img = enemyImage({ art: name, pal });
    BART['enemy_' + name] = img;
  }
  for (const k of ['snow', 'night', 'bamboo', 'mountain', 'sect', 'cave', 'tower', 'tomb', 'abyss']) BART['bg_' + k] = drawBattleBg(k);
  for (const id in BSPR) {
    const S = BSPR[id];
    BART['pose_' + id] = (() => {
      const imgs = [S.idle[0], S.run[1], S.attack, S.cast, S.hurt, S.weak, S.guard, S.win, S.ko];
      const c = makeCanvas(imgs.length * 18, 16);
      imgs.forEach((im, i) => c.getContext('2d').drawImage(im, i * 18, 0));
      return c;
    })();
  }
}
