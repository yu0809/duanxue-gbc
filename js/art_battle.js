// mirror a left half (16 cols) into a symmetric 32-col sprite
function M(rows) { return rows.map((r) => r + Array.from(r).reverse().join('')); }
function patch(rows, x, y, lines) {
  const out = rows.slice();
  lines.forEach((ln, i) => {
    const r = out[y + i];
    out[y + i] = r.slice(0, x) + Array.from(ln).map((c, j) => (c === '?' ? r[x + j] : c)).join('') + r.slice(x + ln.length);
  });
  return out;
}

